/**
 * general.ts — the bank for questions that belong to no topic.
 *
 * ============================================================
 * WHY IT EXISTS
 * ============================================================
 * Itay: "תוסיף בנק מלא ספציפית למורה הפרטי לכל שאלה שלא קשורה ספציפית למסלול
 * הלמידה בנושאים ספציפיים. חשוב שהכל יהיה סופר מדויק."
 *
 * Every other bank in this app is keyed to a topic and, inside it, to a
 * question. That covers a student who is working. It covers nothing for the
 * student standing at the roadmap deciding what to do — and those questions are
 * both the most repetitive in the product and the most expensive, because
 * nothing local could answer them and each one reached the model.
 *
 * ============================================================
 * WHAT MAY AND MAY NOT BE IN HERE
 * ============================================================
 * ⚠️ ONLY ANSWERS THAT ARE TRUE FOR EVERY STUDENT, EVERY DAY. This bank is not
 * keyed to anything, so nothing narrows a wrong answer's blast radius: an entry
 * that is true for a 5-unit student in May is served to a 4-unit student in
 * September too.
 *
 * So: no exam dates, no per-student numbers, no "you should" advice that
 * depends on a plan, and nothing about the syllabus that could change between
 * שאלונים. What is left is method, structure, and how this app works — which is
 * exactly what a student browsing the roadmap actually asks.
 *
 * Anything personal ("על מה כדאי לי לעבוד") belongs to lib/tutor-plan-answer,
 * which reads the student's own plan. Anything about a topic belongs to that
 * topic's bank. This is the remainder, and it is deliberately small: an entry
 * here earns its place by being asked often AND having one correct answer.
 */

