// The REVIEW tile of the four-level plane-trigonometry path. It teaches no new
// machinery: it re-arms the three things every triangle question leans on.
//
//   1. The in-scope identity set (the official list, nothing more):
//        sin(-α)/cos(-α)/tan(-α), the 90°-α family, the 180°-α family,
//        tan = sin/cos, tan·cot = 1, sin²+cos² = 1.
//      sin(180-α)=sin α and cos(180-α)=-cos α are the centrepiece: they are
//      why an obtuse angle behaves as it does and why a sine value is
//      ambiguous. EXCLUDED on purpose: 1+tan², 1+cot², every double angle.
//   2. The circle theorems a trig question leans on — central/inscribed,
//      inscribed on a diameter, tangent ⊥ radius, cyclic quadrilateral,
//      perpendicular from the centre bisects the chord — each with a figure.
//   3. A SHORT refresher on solving sin x = k / cos x = k inside a range
//      (the kind that appears inside a triangle question). The general
//      solution of שאלון 581 is deliberately out of scope.
//
