//
// Our hard rung proves something and then lands on a round number you can check
// in your head. The exam introduces a symbol in one part — $S$, $R$, $\alpha$ —
// and makes you express a later quantity through it. That is a different kind
// of work: nothing to substitute into, and no number to sanity-check against.
//
// Every question here ends that way. They are graded on the COEFFICIENT
// ("שטח המרובע שווה ל-$m \cdot S$; מצאו את $m$"), so the student does the whole
// symbolic chain and the app can still mark it deterministically.
//
